// Writes the single-file build into the Expo app as a TS module, so the app (and the Revyl
// build) never needs to build the game itself. Run via `npm run build` in game/.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(resolve(here, '../dist/index.html'), 'utf8');
const out = resolve(here, '../../src/game/html.ts');
writeFileSync(out, `/* eslint-disable */\n// Generated by game/scripts/embed.mjs. Do not edit; run \`npm run game:build\`.\nexport const GAME_HTML = ${JSON.stringify(html)};\n`);
console.log(`embedded ${(html.length / 1024).toFixed(0)} KB into src/game/html.ts`);
